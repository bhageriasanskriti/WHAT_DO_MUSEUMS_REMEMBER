// Helper to find related objects within same dataset
export function getRelatedObjects(obj: MuseumObject): MuseumObject[] {
  return CURATED_OBJECTS.filter(other => {
    if (other.id === obj.id) return false;
    // Same dataset constraint (as specified in OBJECT_STORY_SPEC.md)
    if (other.dataset !== obj.dataset) return false;
    
    // Check creator
    if (obj.creator && other.creator && obj.creator === other.creator) return true;
    // Check classification or object_type
    if (obj.classification && other.classification && obj.classification === other.classification) return true;
    // Check medium
    if (obj.medium && other.medium && obj.medium === other.medium) return true;
    return false;
  });
}
